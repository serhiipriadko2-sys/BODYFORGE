import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { offlineManifestForFiles, renderOfflineWorker, verifyOfflineWorkerDistribution, OFFLINE_WORKER_FILE } from './offline-worker-build.mjs';
import { MODEL_REQUIREMENT, RUNTIME_FILES, SDK_VERSION } from './offline-pose-pack.mjs';

const root=path.resolve(import.meta.dirname,'..');
const sha=value=>createHash('sha256').update(value).digest('hex');
const entry=(name,text)=>({path:name,bytes:Buffer.byteLength(text),sha256:sha(text)});
const files=[entry('index.html','<html>fixture</html>'),entry('assets/index-Abcd_123.js','export {};'),entry('manifest.webmanifest','{}')];

test('manifest has deterministic canonical identity and exact runtime pins',()=>{
  const a=offlineManifestForFiles(files), b=offlineManifestForFiles([...files].reverse());
  assert.deepEqual(a,b);assert.equal(a.kind,'training');assert.equal(a.entries.length,10);
  assert.equal(a.version,sha(JSON.stringify({schema:1,kind:a.kind,entries:a.entries})));
  const remote=a.entries.filter(e=>e.key.startsWith('https://'));
  assert.equal(remote.length,7);
  for(const pin of RUNTIME_FILES.filter(p=>p.path.startsWith('wasm/'))){
    const key='https://cdn.jsdelivr.net/npm/@mediapipe/tasks-vision@'+SDK_VERSION+'/'+pin.path;
    assert.deepEqual(remote.find(e=>e.key===key),{key,bytes:pin.bytes,sha256:pin.sha256});
  }
  assert.deepEqual(remote.find(e=>e.key===MODEL_REQUIREMENT.url),{
    key:MODEL_REQUIREMENT.url,bytes:MODEL_REQUIREMENT.bytes,sha256:MODEL_REQUIREMENT.sha256,
  });
  const shell=offlineManifestForFiles(files,'shell');
  assert.equal(shell.entries.length,3);assert.notEqual(shell.version,a.version);
  assert.notEqual(offlineManifestForFiles([entry('index.html','changed'),...files.slice(1)]).version,a.version);
});
test('private paths, generated worker self-inclusion, duplicate and forged metadata fail closed',()=>{
  for(const n of ['.env','docs/audits/a.md','../index.html','assets/../index.html','assets/a.png?x=1',
    'assets/con.png','https://invalid.example/a.js','assets/unknown.exe',OFFLINE_WORKER_FILE]){
    assert.throws(()=>offlineManifestForFiles([...files,entry(n,'fixture')]),/offline input entry/);
  }
  assert.throws(()=>offlineManifestForFiles([...files,files[0]]),/offline input entry/);
  assert.throws(()=>offlineManifestForFiles([...files,{...entry('assets/a.jpg','x'),sha256:'bad'}]),/offline input entry/);
  assert.throws(()=>offlineManifestForFiles([...files,{...entry('assets/a.jpg','x'),bytes:33554433}]),/offline input entry/);
  assert.throws(()=>offlineManifestForFiles([...files,entry('assets/index-Abcd_456.js','duplicate entry')]),/offline required inputs/);
  assert.throws(()=>offlineManifestForFiles([files[0],files[1],entry('favicon.svg','<svg/>')]),/offline required inputs/);
  assert.throws(()=>offlineManifestForFiles([...files,...Array.from({length:256},(_,i)=>entry('assets/fixture-'+i+'.jpg','x'))]),/offline cache budget/);
});
test('compiled worker is deterministic JavaScript with embedded immutable inputs',async()=>{
  const manifest=offlineManifestForFiles(files);
  const a=await renderOfflineWorker(root,manifest),b=await renderOfflineWorker(root,manifest);
  assert.equal(a,b);assert.ok(a.length>10000&&a.length<65536);
  assert.doesNotThrow(()=>new vm.Script(a));
  assert.ok(a.includes('worker.attachOfflineWorker(self,'+JSON.stringify(manifest)+');'));
  assert.ok(a.includes('BODYFORGE_OFFLINE_STATUS_V1'));
  assert.ok(!/\b(?:eval|importScripts)\s*\(/.test(a));
});
test('artifact verifier checks exact generated bytes and refuses missing or altered worker',async t=>{
  const dir=fs.mkdtempSync(path.join(fs.realpathSync.native(os.tmpdir()),'bf-offline-build-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true,maxRetries:4,retryDelay:100}));
  fs.mkdirSync(path.join(dir,'src/lib'),{recursive:true});fs.mkdirSync(path.join(dir,'dist'));
  for(const name of ['offlineCache.ts','offlineWorker.ts'])fs.copyFileSync(path.join(root,'src/lib',name),path.join(dir,'src/lib',name));
  const manifest=offlineManifestForFiles(files);
  const text=await renderOfflineWorker(dir,manifest),worker=entry(OFFLINE_WORKER_FILE,text);
  const filename=path.join(dir,'dist',OFFLINE_WORKER_FILE);
  fs.writeFileSync(filename,text);
  const result=await verifyOfflineWorkerDistribution(dir,{files:[...files,worker]});
  assert.equal(result.version,manifest.version);assert.equal(result.workerSha256,worker.sha256);
  assert.equal(result.registration,'not-run');assert.equal(result.inference,'not-run');
  await assert.rejects(verifyOfflineWorkerDistribution(dir,{files}),/missing or duplicate/);
  await assert.rejects(verifyOfflineWorkerDistribution(dir,{files:[...files,worker,worker]}),/missing or duplicate/);
  fs.writeFileSync(filename,text+'//changed');
  await assert.rejects(verifyOfflineWorkerDistribution(dir,{files:[...files,worker]}),/artifact mismatch/);
});

test('exact public notices are offline-pinned without allowing arbitrary text paths',()=>{
  const n=entry('third-party-notices.txt','pinned notice');const m=offlineManifestForFiles([...files,n],'shell');
  assert.deepEqual(m.entries.find(e=>e.key==='/third-party-notices.txt'),{key:'/third-party-notices.txt',bytes:n.bytes,sha256:n.sha256});
  assert.throws(()=>offlineManifestForFiles([...files,entry('private-notices.txt','x')],'shell'),/offline input entry/);
});
