import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { describe, expect, it, vi } from 'vitest';
import { DERMAL_ATTRIBUTE, installDermalRegions, sampleDermalRegion, regionalDermalShaders } from './avatarDermalRegions';
import { avatarSkinShader, installAvatarSkinLighting, installAvatarScanDetail } from './avatarSkinLighting';
import { installAvatarLipResponse } from './avatarLipResponse';
import { applyAvatarFaceForm } from './avatarFace';
import { createAvatarPhysique } from './avatarPhysique';
import { applyAvatarGrowth } from './avatarGrowth';
import { disposeThreeTree } from './threeResources';

describe('regional skin and lip response',()=>{
  it('separates the T-zone, cheek, eyelid, ear and neutral body response',()=>{
    const nose=sampleDermalRegion(.004,1.648,.164);
    const cheek=sampleDermalRegion(.050,1.641,.119);
    const lid=sampleDermalRegion(.030,1.677,.143);
    const ear=sampleDermalRegion(.079,1.654,.049);
    expect(nose[0]).toBeGreaterThan(.9);
    expect(cheek[0]).toBeLessThan(.2);
    expect(ear[1]).toBeGreaterThan(.9);
    expect(cheek[2]).toBeGreaterThan(lid[2]);
    expect(sampleDermalRegion(-.05,1.641,.119)).toEqual(cheek);
    expect(sampleDermalRegion(.3,1.2,.05)).toEqual([0,0,.5]);
    expect(sampleDermalRegion(NaN,1.65,.1)).toEqual([0,0,.5]);
  });
  it('patches the existing physical shader once, preserves the scan and leaves unknown shader anchors untouched',()=>{
    const vertex='#include <begin_vertex>';
    const fragment=avatarSkinShader('#include <lights_physical_pars_fragment>\n#include <roughnessmap_fragment>\n#include <normal_fragment_maps>',true);
    const shader=regionalDermalShaders(vertex,fragment)!;
    expect(shader).toBeDefined();
    expect(shader.fragment).toContain('BODYFORGE_DERMAL_REGIONS_V3');
    expect(shader.fragment).toContain('BODYFORGE_SCAN_MICRO_V2');
    expect(shader.fragment).toContain('BRDF_GGX');
    expect(shader.fragment).toContain('mix(0.28, 0.92, vBfDermal.z)');
    expect(shader.vertex).toContain('vBfDermal = bfDermalRegion');
    expect(regionalDermalShaders(shader.vertex,shader.fragment)).toBeUndefined();
    expect(regionalDermalShaders('unknown',fragment)).toBeUndefined();
    const material=new THREE.MeshPhysicalMaterial();
    material.userData.BODYFORGE_regionalDermal=true;
    installAvatarSkinLighting(material);
    expect(material.customProgramCacheKey()).toContain('regions-v3');
    const scan=new THREE.Texture();installAvatarScanDetail(material,scan);
    expect(material.customProgramCacheKey()).toBe('bodyforge-scan-micro-v2-regions-v3');
    scan.dispose();material.dispose();
  });
  it('binds the real skin and lip response without altering original UV, weights or muscle morphs',async()=>{
    const bytes=Uint8Array.from(readFileSync('public/assets/bodyforge-athlete-efficient.glb'));
    const {scene}=await new GLTFLoader().parseAsync(bytes.buffer,'');
    try{
      const body=scene.getObjectByName('BODYFORGE_Body') as THREE.SkinnedMesh;
      const ears=scene.getObjectByName('BODYFORGE_SkinEars') as THREE.SkinnedMesh;
      const lips=scene.getObjectByName('BODYFORGE_Lips') as THREE.SkinnedMesh;
      expect(applyAvatarFaceForm(scene)).toBeDefined();
      expect(installDermalRegions([body,ears])).toBe(true);
      const field=body.geometry.getAttribute(DERMAL_ATTRIBUTE);
      expect(field.normalized).toBe(true);
      expect(field.count).toBe(65895);
      expect(field.array.byteLength).toBe(65895*3);
      const values=Array.from(field.array);
      const highOil=values.filter((v,i)=>i%3===0&&v>170).length;
      const highScatter=Array.from(ears.geometry.getAttribute(DERMAL_ATTRIBUTE).array).filter((v,i)=>i%3===1&&v>150).length;
      expect(highOil).toBeGreaterThan(50);
      expect(highScatter).toBeGreaterThan(100);
      const pos=lips.geometry.getAttribute('position'), uv=lips.geometry.getAttribute('uv'), weights=lips.geometry.getAttribute('skinWeight');
      const material=lips.material as THREE.MeshStandardMaterial;
      const texture=new THREE.Texture({width:256,height:128});
      const bad=new THREE.Texture({width:2,height:2});
      expect(installAvatarLipResponse([lips],material,bad)).toBe(false);
      bad.dispose();
      expect(installAvatarLipResponse([lips],material,texture)).toBe(true);
      const second=lips.geometry.getAttribute('uv1');
      expect(second.count).toBe(pos.count);
      expect(Array.from(second.array).every(v=>v>=0&&v<=1)).toBe(true);
      expect(lips.geometry.getAttribute('position')).toBe(pos);
      expect(lips.geometry.getAttribute('uv')).toBe(uv);
      expect(lips.geometry.getAttribute('skinWeight')).toBe(weights);
      expect(material.bumpMap).toBe(texture);
      expect(material.roughnessMap).toBe(texture);
      expect(texture.channel).toBe(1);
      expect(texture.colorSpace).toBe(THREE.NoColorSpace);
      expect(installAvatarLipResponse([lips],material,texture)).toBe(false);
      const sculpt=createAvatarPhysique(scene);
      sculpt({arms:5,core:5,legs:5,back:5});
      applyAvatarGrowth(scene,{arms:5,core:5,legs:5,back:5},1);
      expect(body.geometry.getAttribute(DERMAL_ATTRIBUTE)).toBe(field);
      expect(Array.from(field.array)).toEqual(values);
      expect(lips.geometry.getAttribute('uv1')).toBe(second);
      const dispose=vi.spyOn(texture,'dispose');
      disposeThreeTree(scene);
      expect(dispose).toHaveBeenCalledTimes(1);
      console.info('DERMAL_REGIONS',JSON.stringify({bodyVertices:field.count,highOil,highScatter}));
    }finally{disposeThreeTree(scene);}
  });
  it('pins the authored packed lip map at 256 x 128',()=>{
    const bytes=readFileSync('public/assets/athlete-lip-response.png');
    expect(createHash('sha256').update(bytes).digest('hex')).toBe('8a2ca0bb0b5889304cfa03d858c03befb17f900a768b5f9974ddc4608c0ac7fc');
    expect([bytes.readUInt32BE(16),bytes.readUInt32BE(20)]).toEqual([256,128]);
    expect(bytes.length).toBeLessThan(50000);
  });
});
